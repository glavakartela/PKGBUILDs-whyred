"""Set ath10k firmware feature bits in a QCA-ATH10K firmware metadata file.

WCN3990 on whyred loads its firmware externally (the NON_BMI feature bit is
set), so firmware-5.bin is only a small metadata container generated by
ath10k-fwencoder.  ath10k reads the quirk feature bits from it, which allows
enabling driver workarounds for the proprietary firmware without rebuilding
the firmware image itself.

Usage: ath10k-fw-features.py firmware-5.bin BIT [BIT ...]
"""

import struct
import sys

MAGIC = b"QCA-ATH10K\0"
FW_IE_FEATURES = 2
PAD = 0x77


def parse(data):
    if not data.startswith(MAGIC):
        raise SystemExit("not an ath10k firmware metadata file")
    # The kernel aligns the magic (including its NUL) to 4 bytes.
    off = (len(MAGIC) + 3) & ~3
    ies = []
    while off + 8 <= len(data):
        ie_id, ie_len = struct.unpack_from("<II", data, off)
        if off + 8 + ie_len > len(data):
            raise SystemExit("truncated firmware IE")
        ies.append((ie_id, bytearray(data[off + 8:off + 8 + ie_len])))
        off += 8 + ((ie_len + 3) & ~3)
    return ies


def build(ies):
    out = bytearray(MAGIC)
    out.append(PAD)  # padding up to the 4-byte aligned magic length
    for ie_id, payload in ies:
        out += struct.pack("<II", ie_id, len(payload))
        out += payload
        out += bytes([PAD]) * ((-len(payload)) & 3)
    return bytes(out)


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)

    path = sys.argv[1]
    bits = [int(bit, 0) for bit in sys.argv[2:]]
    if any(bit < 0 or bit >= 256 for bit in bits):
        raise SystemExit("feature bit out of range")

    with open(path, "rb") as f:
        data = f.read()

    ies = parse(data)
    nbytes = max((max(bits) + 8) // 8, 1)

    for ie_id, payload in ies:
        if ie_id == FW_IE_FEATURES:
            if len(payload) < nbytes:
                payload += bytes(nbytes - len(payload))
            value = int.from_bytes(payload, "little")
            for bit in bits:
                value |= 1 << bit
            payload[:] = value.to_bytes(len(payload), "little")
            break
    else:
        value = 0
        for bit in bits:
            value |= 1 << bit
        ies.append((FW_IE_FEATURES, bytearray(value.to_bytes(nbytes, "little"))))

    new = build(ies)
    if new != data:
        with open(path, "wb") as f:
            f.write(new)

    print(f"{path}: features = 0x{value:0{len(payload) * 2}x}")


if __name__ == "__main__":
    main()
